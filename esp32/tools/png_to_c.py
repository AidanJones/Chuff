#!/usr/bin/env python3
"""
Convert a Flowey animation sprite sheet PNG to a C header for ESP32 / LVGL.

The sprite sheet must be exactly COLS=30 pixels wide, with frames stacked
vertically — each frame is ROWS=37 pixels tall.  The sprite sheet exported
by animation-editor.html always has this layout.

Usage:
    python png_to_c.py <sprite_sheet.png> <animation_name>

Example:
    python png_to_c.py flowey_blink_sheet.png blink
    → writes flowey_blink.h

The output arrays are uint16_t RGB565, byte-swapped to match the SH8601
display with CONFIG_LV_COLOR_16_SWAP=y.  Render them with:

    esp_lcd_panel_draw_bitmap(panel, 0, 0, COLS, ROWS,
                              flowey_blink_frames[frame_index]);
"""

import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:
    print("Pillow is required.  Install with:  pip install Pillow")
    sys.exit(1)

COLS = 30
ROWS = 37


def rgb_to_rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def byte_swap16(v):
    return ((v & 0xFF) << 8) | ((v >> 8) & 0xFF)


def convert(png_path: str, name: str) -> None:
    img = Image.open(png_path).convert("RGB")
    w, h = img.size

    if w != COLS:
        print(f"ERROR: expected width {COLS}, got {w}")
        sys.exit(1)
    if h % ROWS != 0:
        print(f"ERROR: height {h} is not a multiple of ROWS={ROWS}")
        sys.exit(1)

    n_frames = h // ROWS
    print(f"Found {n_frames} frame(s) in {png_path}")

    guard = f"FLOWEY_{name.upper()}_H"
    lines = [
        f"// Auto-generated by png_to_c.py — do not edit by hand.",
        f"// Source: {Path(png_path).name}  ({n_frames} frames, {COLS}×{ROWS} px, RGB565 byte-swapped)",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <stdint.h>",
        "",
        f"#define FLOWEY_{name.upper()}_N_FRAMES {n_frames}",
        f"#define FLOWEY_ANIM_COLS               {COLS}",
        f"#define FLOWEY_ANIM_ROWS               {ROWS}",
        "",
    ]

    for fi in range(n_frames):
        pixels = []
        for r in range(ROWS):
            for c in range(COLS):
                rgb = img.getpixel((c, fi * ROWS + r))
                pixels.append(byte_swap16(rgb_to_rgb565(*rgb)))

        lines.append(f"static const uint16_t flowey_{name}_f{fi}[{COLS} * {ROWS}] = {{")
        for i in range(0, len(pixels), 8):
            chunk = pixels[i : i + 8]
            lines.append("    " + ", ".join(f"0x{p:04X}" for p in chunk) + ",")
        lines.append("};")
        lines.append("")

    # Pointer array so you can index by frame number at runtime
    lines.append(f"static const uint16_t *const flowey_{name}_frames[{n_frames}] = {{")
    for fi in range(n_frames):
        lines.append(f"    flowey_{name}_f{fi},")
    lines.append("};")
    lines.append("")
    lines.append(f"#endif /* {guard} */")

    out_path = Path(png_path).parent / f"flowey_{name}.h"
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Written to {out_path}")
    print()
    print("Usage in C:")
    print(f"  #include \"flowey_{name}.h\"")
    print(f"  esp_lcd_panel_draw_bitmap(panel, 0, 0, COLS, ROWS,")
    print(f"                            flowey_{name}_frames[frame_index]);")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(1)
    convert(sys.argv[1], sys.argv[2])
