#!/usr/bin/env python3
"""
Convert a pet animation-editor JSON export directly to C headers for ESP32.

Produces one .h file per animation (+ neutral pose), with uint16_t RGB565
byte-swapped arrays matching the SH8601 display (CONFIG_LV_COLOR_16_SWAP=y).

Usage:
    python json_to_c.py <animations.json> [--out-dir <dir>]

Output files (in same directory as JSON, or --out-dir):
    pet_neutral.h     — the neutral / shared pose (1 frame)
    pet_idle.h        — idle animation frames
    pet_blink.h       — blink animation frames
    pet_surprise.h    — surprise animation frames
    pet_anger.h       — anger animation frames
    pet_happy.h       — happy animation frames

Each header exposes:
    PET_<NAME>_N_FRAMES   — number of frames
    pet_<name>_frames[]   — const uint16_t* array indexed by frame number
    PET_ANIM_COLS / PET_ANIM_ROWS — sprite dimensions (30×37)
"""

import sys
import json
import argparse
from pathlib import Path

COLS = 30
ROWS = 37
ANIM_KEYS = ["idle", "blink", "surprise", "anger", "happy"]


def hex_to_rgb(h: str):
    h = h.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def rgb_to_rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def byte_swap16(v):
    return ((v & 0xFF) << 8) | ((v >> 8) & 0xFF)


def frame_to_rgb565(palette, indices):
    result = []
    for idx in indices:
        r, g, b = hex_to_rgb(palette[idx])
        result.append(byte_swap16(rgb_to_rgb565(r, g, b)))
    return result


def write_header(out_path: Path, name: str, frames_rgb565: list, source_name: str):
    guard = f"PET_{name.upper()}_H"
    n = len(frames_rgb565)
    lines = [
        f"// Auto-generated by json_to_c.py — do not edit by hand.",
        f"// Source: {source_name}  ({n} frame(s), {COLS}x{ROWS} px, RGB565 byte-swapped)",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <stdint.h>",
        "",
        f"#define PET_{name.upper()}_N_FRAMES {n}",
        f"#ifndef PET_ANIM_COLS",
        f"#define PET_ANIM_COLS {COLS}",
        f"#define PET_ANIM_ROWS {ROWS}",
        f"#endif",
        "",
    ]

    for fi, pixels in enumerate(frames_rgb565):
        lines.append(f"static const uint16_t pet_{name}_f{fi}[{COLS} * {ROWS}] = {{")
        for i in range(0, len(pixels), 8):
            chunk = pixels[i:i + 8]
            lines.append("    " + ", ".join(f"0x{p:04X}" for p in chunk) + ",")
        lines.append("};")
        lines.append("")

    lines.append(f"static const uint16_t *const pet_{name}_frames[{n}] = {{")
    for fi in range(n):
        lines.append(f"    pet_{name}_f{fi},")
    lines.append("};")
    lines.append("")
    lines.append(f"#endif /* {guard} */")

    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  {out_path}  ({n} frame(s))")


def convert(json_path: str, out_dir: str | None):
    src = Path(json_path)
    data = json.loads(src.read_text(encoding="utf-8"))

    palette = data["palette"]
    out = Path(out_dir) if out_dir else src.parent

    print(f"Converting {src.name} -> {out}/")

    neutral_pixels = frame_to_rgb565(palette, data["shared"])
    write_header(out / "pet_neutral.h", "neutral", [neutral_pixels], src.name)

    for key in ANIM_KEYS:
        if key not in data.get("anims", {}):
            continue
        raw_frames = data["anims"][key]
        frames_rgb565 = [frame_to_rgb565(palette, f) for f in raw_frames]
        write_header(out / f"pet_{key}.h", key, frames_rgb565, src.name)

    print()
    print("Usage: #include \"pet_neutral.h\", pet_neutral_frames[0]")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("json_file", help="Path to animations.json")
    ap.add_argument("--out-dir", default=None, help="Output directory (default: same as JSON)")
    args = ap.parse_args()
    convert(args.json_file, args.out_dir)


if __name__ == "__main__":
    main()
